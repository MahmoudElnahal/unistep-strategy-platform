# Common JSON schema
# ═══════════════════════════════════════════════════════════════════
FORCE_SCHEMA = """
الناتج JSON بالصيغة التالية بالضبط:

{
  "threat_level": "high|medium|low",
  "summary": "ملخص في فقرة (40-60 كلمة)",
  "factors": [
    {"factor": "اسم العامل", "description": "وصف مفصل", "impact": "high|medium|low"}
  ],
  "key_insights": ["رؤية 1", "رؤية 2", "رؤية 3"],
  "strategic_implications": "ماذا يعني هذا للجمعية استراتيجياً؟ (50-80 كلمة)"
}

⚠️ كل النصوص بالعربية الفصحى الاحترافية.
⚠️ استخدم سياق المملكة العربية السعودية.
"""


# ═══════════════════════════════════════════════════════════════════
# Force 1: Direct Rivalry (المنافسة الحالية)
# ═══════════════════════════════════════════════════════════════════
DIRECT_COMPETITORS_PROMPT = """أنت محلل استراتيجي خبير في القطاع غير الربحي السعودي. حلّل **حدّة المنافسة بين المنافسين الحاليين** للجمعية.

في الـ user prompt ستجد قائمة بالجمعيات المنافسة (من تحليل Benchmarking سابق). قيّم:

- عدد المنافسين النشطين في نفس التخصص
- مستوى التشابه في البرامج والخدمات
- التميز النسبي للجمعية (هل مبادراتها فريدة؟)
- التنافس على نفس الفئة المستهدفة الجغرافية
- التنافس على نفس مصادر التمويل
- معدل ابتكار البرامج الجديدة في القطاع
- وجود تخصصات فرعية لم يدخلها أحد بعد (Blue Ocean)

⚠️ لا تخمّن — استخدم البيانات الفعلية المرفقة عن الجمعيات المنافسة.

""" + FORCE_SCHEMA


# ═══════════════════════════════════════════════════════════════════
# Force 2: Substitutes (البدائل)
# ═══════════════════════════════════════════════════════════════════
SUBSTITUTES_PROMPT = """أنت محلل استراتيجي. حلّل **تهديد البدائل** التي قد يلجأ إليها المستفيدون أو الممولون بدلاً من خدمات الجمعية.

اعتبر هذه البدائل المحتملة:

**بدائل للمستفيدين:**
- البرامج الحكومية المباشرة (الضمان الاجتماعي، حساب المواطن)
- مبادرات MSO وشركات CSR (مسؤولية اجتماعية للشركات)
- الأسر الممتدة والدعم العائلي التقليدي
- الفعاليات الخيرية الفردية (مبادرات أفراد)
- المنصات الرقمية للتمويل الجماعي (Crowdfunding)

**بدائل للممولين:**
- التبرع المباشر للأفراد بدون وسيط
- البرامج الحكومية كقناة للمسؤولية الاجتماعية
- الاستثمار الاجتماعي (Impact Investing) بدلاً من التبرع

قيّم احتمال أن يتحول المستفيدون أو الممولون لهذه البدائل.

""" + FORCE_SCHEMA


# ═══════════════════════════════════════════════════════════════════
# Force 3: New Entrants (الوافدون الجدد)
# ═══════════════════════════════════════════════════════════════════
